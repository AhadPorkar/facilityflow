export const locale = () => localStorage.getItem('facilityflow.locale') === 'de' ? 'de' : 'en';
export function setLocale(language) {
  localStorage.setItem('facilityflow.locale', language === 'de' ? 'de' : 'en');
  document.documentElement.lang = locale();
}
export function t(key, params = {}) {
  const value = messages[locale()][key] ?? messages.en[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
export function statusLabel(v) { return t('status_' + v); }
export function priorityLabel(v) { return t('priority_' + v); }
export function typeLabel(v) { return t('type_' + v); }
export function roleLabel(v) { return t('role_' + v); }
